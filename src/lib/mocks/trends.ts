const DAY_MS = 86_400_000;

/** About 60 fictional problems over the last 12 weeks, relative to `now`. */
export function getMockTrendProblems(now = new Date()): AdminProblem[] {
  return ROWS.map(
    ([category, daysAgo, status, bestScore, description], index) => ({
      id: `mock-problem-${String(index + 1).padStart(2, "0")}`,
      description,
      category,
      status,
      bestScore,
      source: bestScore === null ? "mock" : "ai",
      adminNote: null,
      createdAt: new Date(
        now.getTime() - daysAgo * DAY_MS - (index % 9) * 3_600_000,
      ).toISOString(),
    }),
  );
}
